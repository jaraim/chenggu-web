def build_jiazi():
    rows = []
    for i in range(60):
        gz = TIANGAN[i % 10] + DIZHI[i % 12]
        rows.append((i + 1, gz, SHENGXIAO[gz[1]], NAYIN[i // 2]))
    return rows


def get_ganzhi_year(lunar_year):
    gan = TIANGAN[(lunar_year - 4) % 10]
    zhi = DIZHI[(lunar_year - 4) % 12]
    return gan + zhi


def get_shichen(hour):
    if 0 <= hour < 1:
        return '子时'
    if 1 <= hour < 3:
        return '丑时'
    if 3 <= hour < 5:
        return '寅时'
    if 5 <= hour < 7:
        return '卯时'
    if 7 <= hour < 9:
        return '辰时'
    if 9 <= hour < 11:
        return '巳时'
    if 11 <= hour < 13:
        return '午时'
    if 13 <= hour < 15:
        return '未时'
    if 15 <= hour < 17:
        return '申时'
    if 17 <= hour < 19:
        return '酉时'
    if 19 <= hour < 21:
        return '戌时'
    return '亥时'


def weight_text(liang):
    fen = int(round(float(liang) * 10))
    whole, qian = divmod(fen, 10)
    if whole == 0:
        return f"{qian}钱"
    if qian == 0:
        return f"{whole}两"
    return f"{whole}两{qian}钱"


def palace_text(liang):
    fen = int(round(float(liang) * 100))
    whole, rem = divmod(fen, 100)
    qian, fen2 = divmod(rem, 10)
    if whole == 0:
        if qian == 0:
            return f"{fen2}分"
        if fen2 == 0:
            return f"{qian}钱"
        return f"{qian}钱{fen2}分"
    if qian == 0 and fen2 == 0:
        return f"{whole}两"
    if qian == 0:
        return f"{whole}两零{fen2}分"
    if fen2 == 0:
        return f"{whole}两{qian}钱"
    return f"{whole}两{qian}钱{fen2}分"


def standard_bone_weight(solar_year, solar_month, solar_day, hour):
    dt = datetime.datetime(solar_year, solar_month, solar_day, hour)
    if hour >= 23:
        dt += datetime.timedelta(days=1)
        shichen = '子时'
    else:
        shichen = get_shichen(hour)
    lunar = ZhDate.from_datetime(dt)
    gz = get_ganzhi_year(lunar.lunar_year)
    y_w = YEAR_WEIGHT.get(gz, 0)
    m_w = MONTH_WEIGHT.get(lunar.lunar_month, 0)
    d_w = DAY_WEIGHT.get(lunar.lunar_day, 0)
    t_w = SHICHEN_WEIGHT.get(shichen, 0)
    total = round(y_w + m_w + d_w + t_w, 1)
    return {
        'gz': gz, 'lunar_month': lunar.lunar_month, 'lunar_day': lunar.lunar_day,
        'shichen': shichen, 'y': y_w, 'm': m_w, 'd': d_w, 't': t_w, 'total': total,
    }


DIZHI_IDX = {'子': 0, '丑': 1, '寅': 2, '卯': 3, '辰': 4, '巳': 5,
             '午': 6, '未': 7, '申': 8, '酉': 9, '戌': 10, '亥': 11}


def get_day_ganzhi(solar_year, solar_month, solar_day):
    days = (datetime.date(solar_year, solar_month, solar_day)
            - datetime.date(1900, 1, 1)).days
    return TIANGAN[days % 10] + DIZHI[(10 + days) % 12]


def get_month_pillar(lunar_year, lunar_month):
    year_gan = TIANGAN.index(get_ganzhi_year(lunar_year)[0])
    yin_month_gan = (year_gan * 2 + 2) % 10
    month_zhi = (lunar_month + 1) % 12
    month_gan = (yin_month_gan + (month_zhi - 2) % 12) % 10
    return TIANGAN[month_gan] + DIZHI[month_zhi]


def get_hour_pillar(day_ganzhi, shichen):
    day_gan = TIANGAN.index(day_ganzhi[0])
    zi_hour_gan = (day_gan * 2) % 10
    hour_zhi = DIZHI_IDX[shichen[0]]
    hour_gan = (zi_hour_gan + hour_zhi) % 10
    return TIANGAN[hour_gan] + DIZHI[hour_zhi]


def palace_bone_weight(solar_year, solar_month, solar_day, hour):
    dt = datetime.datetime(solar_year, solar_month, solar_day, hour)
    if hour >= 23:
        dt += datetime.timedelta(days=1)
        shichen = '子时'
    else:
        shichen = get_shichen(hour)
    lunar = ZhDate.from_datetime(dt)
    year_p = get_ganzhi_year(lunar.lunar_year)
    month_p = get_month_pillar(lunar.lunar_year, lunar.lunar_month)
    day_p = get_day_ganzhi(dt.year, dt.month, dt.day)
    hour_p = get_hour_pillar(day_p, shichen)
    y_w = PALACE_WEIGHT.get(year_p, 0)
    m_w = PALACE_WEIGHT.get(month_p, 0)
    d_w = PALACE_WEIGHT.get(day_p, 0)
    t_w = PALACE_WEIGHT.get(hour_p, 0)
    total = round(y_w + m_w + d_w + t_w, 2)
    return {
        'year_p': year_p, 'month_p': month_p, 'day_p': day_p, 'hour_p': hour_p,
        'shichen': shichen, 'y': y_w, 'm': m_w, 'd': d_w, 't': t_w, 'total': total,
    }


def get_pillars(solar_year, solar_month, solar_day, hour):
    """便捷函数：返回四柱列表 [年柱,月柱,日柱,时柱]。"""
    p = palace_bone_weight(solar_year, solar_month, solar_day, hour)
    return [p['year_p'], p['month_p'], p['day_p'], p['hour_p']]


