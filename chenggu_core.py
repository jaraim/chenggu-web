def marriage_match(p1, p2):
    """
    两人合婚分析。
    p1, p2: 各自的 palace_bone_weight 返回值（含四柱）。
    返回合婚报告 dict。
    """
    pillars1 = [p1['year_p'], p1['month_p'], p1['day_p'], p1['hour_p']]
    pillars2 = [p2['year_p'], p2['month_p'], p2['day_p'], p2['hour_p']]

    # 1. 生肖配对（年支）
    zhi1, zhi2 = pillars1[0][1], pillars2[0][1]
    pair = ''.join(sorted([zhi1, zhi2]))
    sx1, sx2 = SHENGXIAO[zhi1], SHENGXIAO[zhi2]
    if pair in SHENGXIAO_LIUHE:
        sx_result = f"{sx1}与{sx2}（{zhi1}{zhi2}）为六合，生肖大吉，互相吸引、感情融洽"
        sx_score = 25
    elif pair in SHENGXIAO_LIUCHONG:
        sx_result = f"{sx1}与{sx2}（{zhi1}{zhi2}）为六冲，生肖相冲，性格差异大、易有摩擦"
        sx_score = 5
    elif pair in SHENGXIAO_LIUHAI:
        sx_result = f"{sx1}与{sx2}（{zhi1}{zhi2}）为六害，生肖相害，需多包容、防口舌"
        sx_score = 10
    else:
        sx_result = f"{sx1}与{sx2}（{zhi1}{zhi2}）为普通组合，无大冲大合，相处平稳"
        sx_score = 15

    # 2. 五行互补（两人八字五行合计是否均衡）
    c1, _ = analyze_wuxing(pillars1)
    c2, _ = analyze_wuxing(pillars2)
    combined = {w: c1[w] + c2[w] for w in WUXING_ORDER}
    avg = sum(combined.values()) / 5
    balance = 1 - sum(abs(combined[w] - avg) for w in WUXING_ORDER) / (sum(combined.values()) + 1)
    balance = max(0, min(1, balance))
    wx_score = int(balance * 25)
    missing_combined = [w for w in WUXING_ORDER if combined[w] == 0]
    if missing_combined:
        wx_result = f"两人八字合计仍缺【{'、'.join(missing_combined)}】，五行略有偏颇"
    elif balance > 0.7:
        wx_result = "两人五行互补良好，合计分布均衡，能互相补益"
    else:
        wx_result = "两人五行有一定互补，但分布略不均，可在生活中注意调和"

    # 3. 日柱天干关系（夫妻宫）
    gan1, gan2 = pillars1[2][0], pillars2[2][0]
    w1, w2 = TIANGAN_WUXING[gan1], TIANGAN_WUXING[gan2]
    if w1 == w2:
        rz_result = f"日干{gan1}({w1})与{gan2}({w2})五行相同，为比肩，性格相近、易有竞争"
        rz_score = 12
    elif WUXING_SHENG[w1] == w2:
        rz_result = f"日干{gan1}({w1})生{gan2}({w2})，一方付出较多、能包容对方"
        rz_score = 20
    elif WUXING_SHENG[w2] == w1:
        rz_result = f"日干{gan2}({w2})生{gan1}({w1})，对方对你呵护有加、关系温馨"
        rz_score = 20
    elif WUXING_KE[w1] == w2:
        rz_result = f"日干{gan1}({w1})克{gan2}({w2})，一方较强势、需注意沟通方式"
        rz_score = 8
    else:
        rz_result = f"日干{gan2}({w2})克{gan1}({w1})，对方较有主见、宜柔不宜刚"
        rz_score = 8

    # 4. 骨重匹配
    t1, t2 = p1['total'], p2['total']
    diff = abs(t1 - t2)
    if diff <= 0.3:
        gz_result = f"两人宫位骨重相近（{palace_text(t1)} vs {palace_text(t2)}），命格匹配、步调一致"
        gz_score = 25
    elif diff <= 0.8:
        gz_result = f"两人骨重有差异（{palace_text(t1)} vs {palace_text(t2)}），可互补长短"
        gz_score = 18
    else:
        gz_result = f"两人骨重差异较大（{palace_text(t1)} vs {palace_text(t2)}），人生节奏不同，需互相理解"
        gz_score = 10

    total_score = sx_score + wx_score + rz_score + gz_score
    if total_score >= 80:
        level = "天作之合"
        advice = "两人缘分深厚，各方面匹配度高，珍惜缘分、互相扶持，婚姻美满。"
    elif total_score >= 65:
        level = "良缘佳配"
        advice = "整体匹配良好，虽有小差异但能互补，多沟通包容，可成佳偶。"
    elif total_score >= 50:
        level = "中等姻缘"
        advice = "有缘分基础但也存在挑战，需要双方共同经营，多换位思考、化解摩擦。"
    else:
        level = "需多磨合"
        advice = "两人差异较大，需付出更多耐心和包容，建议深入了解后再做决定。"

    return {
        'score': total_score, 'level': level, 'advice': advice,
        'shengxiao': sx_result, 'shengxiao_score': sx_score,
        'wuxing': wx_result, 'wuxing_score': wx_score, 'wuxing_combined': combined,
        'rizhu': rz_result, 'rizhu_score': rz_score,
        'guzhong': gz_result, 'guzhong_score': gz_score,
        'p1_pillars': pillars1, 'p2_pillars': pillars2,
    }


