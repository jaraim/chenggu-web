    double_names = []
    for i in range(len(chars)):
        for j in range(i + 1, len(chars)):
            double_names.append(surname + chars[i] + chars[j])
            if len(double_names) >= 12:
                break
        if len(double_names) >= 12:
            break

    return count, day_master, xi, reason, single_names, double_names


